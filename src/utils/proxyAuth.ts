import { createHmac, timingSafeEqual } from "crypto";

const MAX_PROXY_SIG_AGE_MS = 30_000;

function getProxySecret(): string | null {
  const secret = process.env.INTERNAL_PROXY_SECRET?.trim();
  if (!secret || secret.length < 16) {
    return null;
  }
  return secret;
}

/**
 * Generates a short-lived HMAC-SHA256 signature for user identity claims injected by Edge Proxy.
 * Never falls back to public keys or hardcoded secrets.
 */
export function signProxyUser(
  userId: string,
  role: string,
  isActive: boolean,
  email: string,
  timestampMs: number
): string | null {
  const secret = getProxySecret();
  if (!secret) return null;

  return createHmac("sha256", secret)
    .update(`${userId}:${role}:${isActive ? "true" : "false"}:${email}:${timestampMs}`)
    .digest("hex");
}

/**
 * Validates an HMAC-SHA256 signature and freshness window to guarantee headers were
 * generated by internal proxy middleware and cannot be forged or replayed.
 */
export function verifyProxyUser(
  userId: string,
  role: string,
  isActive: boolean,
  email: string,
  timestampHeader: string | null,
  signature: string | null
): boolean {
  const secret = getProxySecret();
  if (!secret || !signature || typeof signature !== "string" || !timestampHeader) {
    return false;
  }

  const ts = Number(timestampHeader);
  if (!Number.isFinite(ts) || Math.abs(Date.now() - ts) > MAX_PROXY_SIG_AGE_MS) {
    return false;
  }

  try {
    const expected = signProxyUser(userId, role, isActive, email, ts);
    if (!expected) return false;
    const sigBuf = Buffer.from(signature, "hex");
    const expBuf = Buffer.from(expected, "hex");
    if (sigBuf.length === 0 || sigBuf.length !== expBuf.length) return false;
    return timingSafeEqual(sigBuf, expBuf);
  } catch {
    return false;
  }
}
